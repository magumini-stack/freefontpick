"""우리 서버에서 파일을 내보내면 안 되는 폰트 — 다운로드는 제작사 배포처로.

무엇을 담나
-----------
상세페이지 라이선스 표에서 '재배포'가 막혀 있거나 아직 확인되지 않았는데,
배포용 ZIP 이 올라가 있던 폰트다. 값은 그 폰트의 **제작사 배포 페이지**다.

왜 코드에 적나
-------------
어드민에서 파일을 지우는 것만으로는 부족하다. 나중에 누가 다시 올리면 그
순간 다시 위반으로 돌아간다. 이 목록은 어드민이 정하는 입력값이 아니라
지켜야 하는 조건이라 코드에 남긴다. 라이선스를 확인해 재배포가 허용되는
것으로 밝혀지면 그때 여기서 지운다.

배포처 주소까지 함께 두는 이유
---------------------------
DB 의 배포처(Font.url)가 구글 드라이브 사본을 가리키고 있었다. 파일 배포만
막고 링크를 그대로 두면 재배포 금지 폰트를 드라이브 사본으로 안내하는 셈이라
문제가 옮겨 갈 뿐이다. 그래서 여기 적힌 주소가 DB 값을 이긴다.
어드민에서 배포처를 제대로 고치면 이 값과 같아지고, 그때는 여기서 빼도 된다.

내부 렌더링은 막지 않는다
----------------------
og:image 를 그리려면 폰트 파일을 읽어야 한다(og_image.py 는 파일이 없을 때
ZIP 을 마지막 수단으로 쓴다 — 함렛이 그 경우다). 그림을 만드는 것은 파일을
남에게 넘기는 일이 아니므로 resolve_zip 자체는 건드리지 않는다. 막는 것은
'파일을 내려주는 자리'뿐이다.
"""

NO_REDISTRIBUTE = {
    # 라이선스 원문: "the font data itself may not be redistributed sold at any
    # measure or time in any form." 표에도 재배포 '불가'로 확인돼 있다.
    118: "https://www.dafont.com/caviar-dreams.font",
    # 표에 재배포·수정 모두 '불가'. 제작자(Khurasan)의 배포 페이지로 보낸다.
    219: "https://www.dafont.com/notedry.font",
    # 우리 표가 재배포·수정을 '확인 필요'로 두고 있다. 같은 페이지 소개문은
    # "재배포가 자유롭고"라고 적어 두 말이 어긋난다. 확인 전까지는 내보내지
    # 않고 제작사 저장소로 보낸다.
    182: "https://github.com/hyper-type/hahmlet",
}


def official_url(font_id: int) -> str:
    """제작사 배포처. 목록에 없으면 빈 문자열."""
    return NO_REDISTRIBUTE.get(font_id, "")


def blocked(font_id: int) -> bool:
    return font_id in NO_REDISTRIBUTE
