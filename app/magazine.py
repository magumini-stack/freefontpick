def file_src(file: str) -> str:
    """그림 한 장의 경로. 파일이 바뀌면 뒤에 붙는 값이 바뀌어 캐시가 저절로
    풀린다. 파일이 없으면 경로만 준다 — 그림 없이도 글은 나와야 한다."""
    if not file:
        return ""
    p = Path(__file__).resolve().parent.parent / "static" / "mz" / file
    try:
        return "/mz/%s?v=%d" % (file, int(p.stat().st_mtime))
    except OSError:
        return "/mz/%s" % file


def image_src(post) -> str:
    """대표 그림의 경로."""
    im = post.get("image")
    return file_src(im["file"]) if im else ""


