def image_src(post) -> str:
    """글 그림의 경로. 파일이 바뀌면 뒤에 붙는 값이 바뀌어 캐시가 저절로 풀린다.
    파일이 없으면 빈 문자열 — 그림 없이도 글은 나와야 한다."""
    im = post.get("image")
    if not im:
        return ""
    p = Path(__file__).resolve().parent.parent / "static" / "mz" / im["file"]
    try:
        return "/mz/%s?v=%d" % (im["file"], int(p.stat().st_mtime))
    except OSError:
        return "/mz/%s" % im["file"]


